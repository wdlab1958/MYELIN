#!/usr/bin/env bash
# MYELIN v1.0 installer (P8-T3). Idempotent; never overwrites user files (backs up instead).
#
#   scripts/install.sh [--vault <path>] [--bin <dir>] [--no-web] [--no-plugin] [--no-mcp] [--dry-run]
#
# What it does
#   1. checks python3.12 (and that asyncio works — mixed pyenv installs segfault), uv, git, node (for the Hub web)
#   2. uv sync --all-packages ; builds the Hub web (unless --no-web)
#   3. writes launchers myelin / myelin-mcp / myelin-hub into --bin (default ~/.local/bin)
#   4. registers the Claude Code plugin from the local marketplace (unless --no-plugin)
#   5. registers the MCP server for the vault (unless --no-mcp / no --vault)
#   6. copies the Obsidian theme into <vault>/.obsidian/themes/MYELIN Emboss (if --vault)
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VAULT=""; BIN="${HOME}/.local/bin"; WEB=1; PLUGIN=1; MCP=1; DRY=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --vault) VAULT="$2"; shift 2;;
    --bin) BIN="$2"; shift 2;;
    --no-web) WEB=0; shift;;
    --no-plugin) PLUGIN=0; shift;;
    --no-mcp) MCP=0; shift;;
    --dry-run) DRY=1; shift;;
    -h|--help) sed -n '2,12p' "$0"; exit 0;;
    *) echo "unknown option: $1" >&2; exit 2;;
  esac
done
run() { if [[ $DRY -eq 1 ]]; then echo "+ $*"; else "$@"; fi; }
say() { echo "▸ $*"; }
die() { echo "✗ $*" >&2; exit 1; }

# 1. prerequisites
PY="$(command -v python3.12 || command -v python3 || true)"
[[ -n "$PY" ]] || die "python3.12 not found"
"$PY" - <<'PYEOF' || die "python asyncio self-test failed — this interpreter is a mixed install (see PHASE_STATE P4). Use /usr/bin/python3.12 or reinstall pyenv 3.12."
import asyncio, sys
assert sys.version_info[:2] == (3, 12), sys.version
async def f(): return 1
assert asyncio.run(f()) == 1
PYEOF
say "python: $("$PY" -c 'import sys; print(sys.executable, sys.version.split()[0])')"
command -v uv >/dev/null || die "uv not found (https://docs.astral.sh/uv/)"
command -v git >/dev/null || die "git not found"
if [[ $WEB -eq 1 ]] && ! command -v npm >/dev/null; then say "npm not found — skipping Hub web build (--no-web)"; WEB=0; fi
export UV_PYTHON="$PY"

# 2. sync + build
run uv --directory "$REPO" sync --all-packages
if [[ $WEB -eq 1 ]]; then
  run npm install --prefix "$REPO/packages/myelin-hub/web" --no-audit --no-fund --loglevel=error
  run npm run --prefix "$REPO/packages/myelin-hub/web" build
fi

# 3. launchers (never clobber a file we did not write)
run mkdir -p "$BIN"
for cmd in myelin myelin-mcp myelin-hub; do
  target="$BIN/$cmd"
  body="#!/usr/bin/env bash
# generated by MYELIN scripts/install.sh — launches $cmd from $REPO
export UV_PYTHON=\"\${UV_PYTHON:-$PY}\"
exec uv --directory \"$REPO\" run $cmd \"\$@\"
"
  if [[ -e "$target" ]] && ! grep -q "generated by MYELIN" "$target" 2>/dev/null; then
    say "$target exists and is not ours — leaving it, writing $target.myelin instead"; target="$target.myelin"
  fi
  if [[ $DRY -eq 1 ]]; then echo "+ write $target"; else printf '%s' "$body" > "$target"; chmod +x "$target"; fi
done
say "launchers in $BIN (add to PATH if needed)"

# 4. Claude Code plugin (local marketplace)
if [[ $PLUGIN -eq 1 ]] && command -v claude >/dev/null; then
  run claude plugin marketplace add "$REPO" || say "marketplace already added or claude too old — use: claude --plugin-dir $REPO/plugin"
  run claude plugin install myelin@myelin-local --scope user || say "plugin install skipped — fallback: claude --plugin-dir $REPO/plugin"
  run claude plugin validate "$REPO/plugin" --strict
elif [[ $PLUGIN -eq 1 ]]; then
  say "claude CLI not found — install Claude Code, then: claude --plugin-dir $REPO/plugin"
fi

# 5. MCP + 6. theme (vault-specific)
if [[ -n "$VAULT" ]]; then
  [[ -f "$VAULT/myelin.yaml" ]] || say "$VAULT is not a Vault yet — run: $BIN/myelin init --vault \"$VAULT\" (or myelin-hub onboarding)"
  if [[ $MCP -eq 1 ]] && command -v claude >/dev/null; then
    run claude mcp add myelin --scope user -- uv --directory "$REPO" run myelin-mcp --vault "$VAULT" || say "mcp add skipped (already registered?)"
  fi
  theme_dir="$VAULT/.obsidian/themes/MYELIN Emboss"
  run mkdir -p "$theme_dir"
  for f in manifest.json theme.css; do
    src="$REPO/theme/obsidian-myelin-emboss/$f"; dst="$theme_dir/$f"
    if [[ -e "$dst" ]] && ! cmp -s "$src" "$dst"; then run cp "$dst" "$dst.bak"; fi
    run cp "$src" "$dst"
  done
  say "Obsidian theme → $theme_dir (Settings › Appearance › Themes › MYELIN Emboss)"
fi
say "done. next: $BIN/myelin-hub --vault <vault>  →  http://127.0.0.1:8787"
