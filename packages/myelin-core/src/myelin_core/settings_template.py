"""Vault `.claude/settings.json` template — second line of defence behind the Guard.

ADR-0002 D5/D6.

- `Edit(path)` deny rules cover Edit, Write and NotebookEdit (a `Write(...)` rule is never
  consulted by Claude Code, so only `Edit(...)` is used).
- Bash prefix denies catch the obvious overwrite/destroy commands; the real enforcement is
  `plugin/hooks/guard_bash.py`, because prefix matching cannot see `/bin/rm`, pipes or heredocs.
- `Read(path)` deny rules are consulted for Read and, best-effort, Grep/Glob/LSP (and also block
  Edit/Write there). `Grep(...)`/`Glob(...)` path rules are accepted but never evaluated, so the
  confidential-routing fallback for 40_IP/** is a single `Read(./40_IP/**)` rule (ADR-0011 §4).
  A `classification: confidential` note outside 40_IP cannot be expressed as a path rule; only the
  Guard hook (`plugin/hooks/guard_read.py`) covers it.
"""

from __future__ import annotations

import json

HUMAN_ONLY_PATHS: tuple[str, ...] = (
    "./10_Domains/**",
    "./20_Projects/**",
    "./30_Resources/**",
    "./40_IP/**",
    "./90_System/**",
    "./99_Archive/**",
    "./myelin.yaml",
    "./CLAUDE.md",
    "./.claude/**",
    "./.myelin/**",
)

# ADR-0011: 40_IP/** is routed to a local LLM; an external Claude Code session may not read it.
LOCAL_ONLY_READ_PATHS: tuple[str, ...] = ("./40_IP/**",)

BASH_DENY: tuple[str, ...] = (
    "Bash(rm *)",
    "Bash(rmdir *)",
    "Bash(mv *)",
    "Bash(cp *)",
    "Bash(sed -i*)",
    "Bash(tee *)",
    "Bash(truncate *)",
    "Bash(git push *)",
    "Bash(git reset *)",
    "Bash(git checkout *)",
    "Bash(git restore *)",
    "Bash(git clean *)",
    "Bash(git stash *)",
    "Bash(chmod *)",
    "Bash(chown *)",
)


def claude_settings() -> dict[str, object]:
    return {
        "$comment": (
            "MYELIN Vault policy (generated by `myelin init`; ADR-0002 D5/D6). "
            "Edit(...) denies cover Write/Edit/NotebookEdit; Read(./40_IP/**) keeps 40_IP out of "
            "Read/Grep/Glob in every session (ADR-0011; LOCAL sessions use the plugin Guard "
            "with MYELIN_LLM=local and may override this in settings.local.json). "
            "The MYELIN plugin Guard hooks are the "
            "primary enforcement; these rules are the fallback. Personal overrides go to "
            "settings.local.json (git-ignored)."
        ),
        "permissions": {
            "deny": [
                *(f"Edit({p})" for p in HUMAN_ONLY_PATHS),
                *(f"Read({p})" for p in LOCAL_ONLY_READ_PATHS),
                *BASH_DENY,
            ],
            "ask": [
                "Bash(git commit *)",
                "Bash(python *)",
                "Bash(python3 *)",
                "Bash(uv run python *)",
                "Bash(node *)",
                "Bash(bash *)",
                "Bash(sh *)",
                "Bash(perl *)",
                "Bash(ruby *)",
                "Bash(curl *)",
                "Bash(wget *)",
            ],
            "defaultMode": "default",
        },
    }


def render_claude_settings() -> str:
    return json.dumps(claude_settings(), ensure_ascii=False, indent=2) + "\n"
