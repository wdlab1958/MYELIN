"""P8-T3 — install.sh: dry-run lists steps; real run writes launchers + theme idempotently."""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts/install.sh"


def _run(args: list[str], home: Path) -> subprocess.CompletedProcess[str]:
    env = {**os.environ, "HOME": str(home), "UV_PYTHON": sys.executable}
    return subprocess.run(
        ["bash", str(SCRIPT), *args], cwd=ROOT, env=env, capture_output=True, text=True
    )


def test_dry_run_lists_steps(tmp_path: Path) -> None:
    r = _run(
        ["--dry-run", "--no-web", "--no-plugin", "--no-mcp", "--vault", str(tmp_path / "v")],
        tmp_path,
    )
    assert r.returncode == 0, r.stderr
    assert "+ uv --directory" in r.stdout and "+ write" in r.stdout and "theme" in r.stdout
    assert not (tmp_path / ".local/bin/myelin").exists()


def test_install_launchers_and_theme_idempotent(tmp_path: Path) -> None:
    vault = tmp_path / "v"
    vault.mkdir()
    binp = tmp_path / "bin"
    (binp).mkdir()
    (binp / "myelin").write_text(
        "#!/bin/sh\necho mine\n", encoding="utf-8"
    )  # pre-existing foreign file
    r = _run(
        ["--no-web", "--no-plugin", "--no-mcp", "--vault", str(vault), "--bin", str(binp)], tmp_path
    )
    assert r.returncode == 0, r.stderr + r.stdout
    assert (
        (binp / "myelin").read_text(encoding="utf-8").startswith("#!/bin/sh\necho mine")
    )  # untouched
    assert (
        (binp / "myelin.myelin").exists()
        and (binp / "myelin-hub").exists()
        and (binp / "myelin-mcp").exists()
    )
    launcher = (binp / "myelin-hub").read_text(encoding="utf-8")
    assert "generated by MYELIN" in launcher and "run myelin-hub" in launcher
    theme = vault / ".obsidian/themes/MYELIN Emboss"
    assert (theme / "theme.css").exists() and (theme / "manifest.json").exists()
    (theme / "theme.css").write_text("user edited", encoding="utf-8")
    r = _run(
        ["--no-web", "--no-plugin", "--no-mcp", "--vault", str(vault), "--bin", str(binp)], tmp_path
    )
    assert r.returncode == 0, r.stderr
    assert (theme / "theme.css.bak").read_text(
        encoding="utf-8"
    ) == "user edited"  # backed up, not lost
    assert (theme / "theme.css").read_text(encoding="utf-8") != "user edited"
    assert "not a Vault yet" in r.stdout


def test_marketplace_manifest_points_at_plugin() -> None:
    import json

    m = json.loads((ROOT / ".claude-plugin/marketplace.json").read_text(encoding="utf-8"))
    assert m["name"] == "myelin-local" and m["plugins"][0]["source"] == "./plugin"
    assert m["plugins"][0]["name"] == "myelin"


def test_install_obsidian_script_is_sane() -> None:
    """install_obsidian.sh: valid bash, documented usage, never runs the obsidian binary."""
    script = ROOT / "scripts/install_obsidian.sh"
    assert subprocess.run(["bash", "-n", str(script)], capture_output=True).returncode == 0
    r = subprocess.run(["bash", str(script), "--help"], capture_output=True, text=True)
    assert r.returncode == 0 and "--vault" in r.stdout
    text = script.read_text(encoding="utf-8")
    assert "obsidian --version" not in text  # it opens the GUI and blocks (found the hard way)
    assert "obsidianmd/obsidian-releases" in text and "cssTheme" in text
    assert subprocess.run(["bash", str(script), "--bogus"], capture_output=True).returncode == 2
